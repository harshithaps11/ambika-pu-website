export function isDatabaseConfigured(): boolean {
  const url = process.env.DATABASE_URL;
  if (!url) return false;
  if (
    url.includes("HOST") ||
    url.includes("USER:PASSWORD") ||
    url.includes("DBNAME") ||
    url.includes("replace-with")
  ) {
    return false;
  }
  return true;
}

